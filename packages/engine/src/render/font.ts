/** Per-glyph advance in pixels. The factory default is 8; three glyphs ship wrong on purpose. */
const ADVANCE: Record<string, number> = { I: 10, W: 7, J: 9 };

export const GLYPH_W = 8;
export const GLYPH_H = 8;

export interface Glyph {
  bits: Uint8Array;
  advance: number;
}

const cache = new Map<string, Glyph>();

export function glyph(ch: string): Glyph {
  let c = ch.toUpperCase();
  if (c === "’" || c === "‘") c = "'";
  if (c === "“" || c === "”") c = '"';
  if (c === "—" || c === "–") c = "-";
  let g = cache.get(c);
  if (g) return g;
  const src = G[c] ?? G["?"]!;
  const bits = new Uint8Array(64);
  src.split("|").forEach((row, y) => {
    for (let x = 0; x < 8; x++) bits[y * 8 + x] = row[x] === "#" ? 1 : 0;
  });
  g = { bits, advance: ADVANCE[c] ?? 8 };
  cache.set(c, g);
  return g;
}

export function textWidth(text: string, scale = 1): number {
  let w = 0;
  for (const ch of text) w += glyph(ch).advance;
  return w * scale;
}

/** Calls `plot(x, y)` for every ink pixel of the text drawn at (x, y) with top-left origin. */
export function rasterText(
  text: string,
  x: number,
  y: number,
  scale: number,
  plot: (px: number, py: number) => void,
): void {
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    for (let gy = 0; gy < 8; gy++)
      for (let gx = 0; gx < 8; gx++)
        if (g.bits[gy * 8 + gx])
          for (let sy = 0; sy < scale; sy++)
            for (let sx = 0; sx < scale; sx++) plot(cx + gx * scale + sx, y + gy * scale + sy);
    cx += g.advance * scale;
  }
}

